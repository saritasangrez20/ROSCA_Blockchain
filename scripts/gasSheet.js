// Builds the gas sheet (docs/gas/gas_sheet.md and .csv) from the measurement files written by
// scripts/measureGas.js. Plain Node, no chain needed: node scripts/gasSheet.js
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "..", "docs", "gas");
const load = (f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));

const columns = [
  ["Baseline", load("baseline.json")],
  ["+G1 clones", load("steps/01_clones.json")],
  ["+G2 packing", load("steps/02_packing.json")],
  ["+G3 bitmap", load("steps/03_bitmap.json")],
  ["+G4 events", load("steps/04_reputation_events.json")],
  ["Final (+S1-S3)", load("final.json")],
];
const base = columns[0][1];
const fin = columns[columns.length - 1][1];

const LABELS = {
  createCircle: "W1 createCircle",
  join_first: "W2 join (first member)",
  join_middle: "W2 join (middle member)",
  join_last_starts_draw: "W2 join (last member, starts draw)",
  commit: "W3 commit",
  reveal_first: "W3 reveal (first)",
  reveal_last: "W3 reveal (last)",
  finalizeDraw: "W3 finalizeDraw",
  contribute_first_in_round: "W4 contribute (first in round)",
  contribute_later_in_round: "W4 contribute (later in round)",
  settleRound_allPaid: "W5 settleRound (all paid)",
  settleRound_oneDefault: "W5 settleRound (one default)",
  claimPayout: "W6 claimPayout",
  settleRound_last_completes: "W5+W7 last settleRound (completes)",
};

const fmt = (n) => Number(n).toLocaleString("en-US");
const pct = (a, b) => {
  const v = ((b - a) / a) * 100;
  return `${v > 0 ? "+" : ""}${v.toFixed(1)}%`;
};

const rows = Object.keys(LABELS).map((k) => [LABELS[k], ...columns.map(([, j]) => j.gas[k]), pct(base.gas[k], fin.gas[k])]);
rows.push(["Whole circle (every transaction)", ...columns.map(([, j]) => j.lifecycleTotal), pct(base.lifecycleTotal, fin.lifecycleTotal)]);

const header = ["Operation", ...columns.map(([n]) => n), "Change"];
let md = "# Gas sheet\n\n";
md += "Generated by `node scripts/gasSheet.js` from the files written by `scripts/measureGas.js`.\n";
md += `Solidity ${base.solc}, optimizer on, ${base.optimizerRuns} runs. Scenario: ${base.scenario}.\n`;
md += "Every action is chosen by payout position, so the numbers do not depend on the random draw.\n";
md += "Columns are cumulative: each one adds one optimization to the previous column. The last column\n";
md += "also contains the three security fixes (S1 pause, S2 draw, S3 admin role), which cost a little gas.\n\n";
md += "## Gas per call\n\n";
md += `| ${header.join(" | ")} |\n| ${header.map((_, i) => (i === 0 ? "---" : "---:")).join(" | ")} |\n`;
for (const r of rows) md += `| ${r.map((v, i) => (i === 0 || i === r.length - 1 ? v : fmt(v))).join(" | ")} |\n`;

md += "\n## One off deployment\n\n| Contract | Baseline | Final | Change |\n| --- | ---: | ---: | ---: |\n";
for (const k of Object.keys(base.deploy)) {
  md += `| ${k} | ${fmt(base.deploy[k])} | ${fmt(fin.deploy[k])} | ${pct(base.deploy[k], fin.deploy[k])} |\n`;
}
const perCircle = base.gas.createCircle - fin.gas.createCircle;
const extraDeploy = fin.deploy.total - base.deploy.total;
md += `\nThe factory now deploys the Circle implementation once, so deployment costs ${fmt(extraDeploy)} more gas;\n`;
md += `each circle saves ${fmt(perCircle)} gas on creation, so the extra cost is repaid by the first circle.\n`;

md += "\n## Bytecode size (bytes, limit 24,576)\n\n| Contract | Baseline | Final |\n| --- | ---: | ---: |\n";
for (const k of Object.keys(base.sizes)) md += `| ${k} | ${fmt(base.sizes[k])} | ${fmt(fin.sizes[k])} |\n`;

md += `
## What each optimization does

| Id | Optimization | Where | Why it saves gas |
| --- | --- | --- | --- |
| G1 | EIP 1167 minimal proxy clones | CircleFactory | A circle is 45 bytes of code that delegates to one implementation, instead of deploying about 16.5 KB of bytecode per circle. Costs about 2.7k extra per call (delegatecall). |
| G2 | Storage packing and immutables | Circle, BaseCircleLifecycle, PayoutOrder, ReputationRegistry | Fewer storage slots: configuration and round timing in three slots instead of nine, one slot per member (position, removed, defaults), one slot per round result, one slot for a draw's flags, deadlines and counters, one slot for a reputation record. Module addresses are immutables of the implementation, so they cost no storage. A new slot costs 22,100 gas; updating an already used slot costs 2,900 to 5,000. |
| G3 | Paid bitmap | Circle | Who paid a round is one uint256 (bit per payout position) instead of a nested mapping of bools plus a counter: one storage write per payment instead of two, one read per settlement instead of one per member. |
| G4 | Events only reputation history | ReputationRegistry | The per entry history was pushed to a storage array (two new slots plus a length update per entry); the ReputationUpdated event already carries it and the indexer rebuilds it. |
| (evaluated) | Custom errors | all | Not applied: revert strings only cost gas when a call fails, and with clones the bytecode is deployed once. Keeping the strings keeps Member B's error decoder and every revert test unchanged. |
`;

fs.writeFileSync(path.join(dir, "gas_sheet.md"), md);
const csv = [header, ...rows].map((r) => r.join(",")).join("\n") + "\n";
fs.writeFileSync(path.join(dir, "gas_sheet.csv"), csv);
console.log(md);
